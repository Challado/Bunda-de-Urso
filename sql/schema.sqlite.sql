-- T01 UF
CREATE TABLE IF NOT EXISTS UF (
    sigla CHAR(2) PRIMARY KEY NOT NULL CHECK (sigla IN ('AC', 'AL', 'AP', 'AM', 'BA', 'CE', 'DF', 'ES', 'GO', 'MA', 'MT', 'MS', 'MG', 'PA', 'PB', 'PR', 'PE', 'PI', 'RJ', 'RN', 'RS', 'RO', 'RR', 'SC', 'SP', 'SE', 'TO')),
    nome TEXT NOT NULL UNIQUE
);

-- T02 MUNICIPIO
CREATE TABLE IF NOT EXISTS MUNICIPIO (
    codigo_ibge CHAR(7) PRIMARY KEY NOT NULL,
    uf_sigla CHAR(2) NOT NULL REFERENCES UF(sigla) ON DELETE RESTRICT,
