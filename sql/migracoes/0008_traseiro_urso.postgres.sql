-- TRASEIRO DE URSO: identidades, diario imutavel, fila e decisoes locais.
CREATE TABLE IF NOT EXISTS TRASEIRO_LOCAL (
 singleton INTEGER PRIMARY KEY CHECK (singleton=1),
 uuid TEXT NOT NULL UNIQUE,
 criado_em TEXT NOT NULL,
 aviso_hash TEXT,
 aviso_em TEXT
);
CREATE TABLE IF NOT EXISTS TRASEIRO_INSTANCIA (
 uuid TEXT PRIMARY KEY,
 api_url TEXT NOT NULL UNIQUE,
 nome TEXT NOT NULL,
 aplicacao TEXT NOT NULL DEFAULT 'Sistema externo',
 estado TEXT NOT NULL DEFAULT 'ativo' CHECK (estado IN ('ativo','inativo','bloqueado','pausado')),
 criado_em TEXT NOT NULL,
 ultimo_contato TEXT,
 ultima_tentativa TEXT,
 falhas INTEGER NOT NULL DEFAULT 0 CHECK (falhas>=0),
 cursor_entrada INTEGER NOT NULL DEFAULT 0 CHECK (cursor_entrada>=0),
 cursor_saida INTEGER NOT NULL DEFAULT 0 CHECK (cursor_saida>=0),
 ultimo_erro TEXT,
 intervalo_segundos INTEGER NOT NULL DEFAULT 300 CHECK (intervalo_segundos>=1),
 lote INTEGER NOT NULL DEFAULT 100 CHECK (lote>=1),
 max_bytes INTEGER NOT NULL DEFAULT 2097152 CHECK (max_bytes>=1024),
 parada_anunciada INTEGER NOT NULL DEFAULT 0 CHECK (parada_anunciada IN (0,1)),
 anuncio_id TEXT,
 pausa_inicio TEXT,
 pausa_fim TEXT,
 ultima_consulta_recebida TEXT
);
CREATE TABLE IF NOT EXISTS TRASEIRO_EVENTO (
 seq BIGSERIAL PRIMARY KEY,
 uuid TEXT NOT NULL UNIQUE,
 origem TEXT NOT NULL,
 tipo TEXT NOT NULL CHECK (tipo IN ('radar.v1','fonte-coleta.v1')),
 chave TEXT NOT NULL,
 revisao INTEGER NOT NULL CHECK (revisao>0),
 acao TEXT NOT NULL CHECK (acao IN ('publicar','retirar')),
 documento TEXT NOT NULL,
 hash_documento TEXT NOT NULL,
 recebido_via TEXT REFERENCES TRASEIRO_INSTANCIA(uuid) ON DELETE RESTRICT,
 recebido_em TEXT NOT NULL,
 UNIQUE(origem,tipo,chave,revisao)
);
CREATE TABLE IF NOT EXISTS TRASEIRO_CADASTRO (
 id BIGSERIAL PRIMARY KEY,
 origem TEXT NOT NULL,
 chave TEXT NOT NULL,
 evento_id INTEGER NOT NULL REFERENCES TRASEIRO_EVENTO(seq) ON DELETE RESTRICT,
 validado_evento_id INTEGER REFERENCES TRASEIRO_EVENTO(seq) ON DELETE RESTRICT,
 ponto_id INTEGER REFERENCES PONTO_FISCALIZACAO(id) ON DELETE RESTRICT,
 estado TEXT NOT NULL DEFAULT 'pendente' CHECK (estado IN ('pendente','aprovado','rejeitado','retirado')),
 UNIQUE(origem,chave)
);
CREATE TABLE IF NOT EXISTS TRASEIRO_FONTE (
 id BIGSERIAL PRIMARY KEY,
 origem TEXT NOT NULL,
 chave TEXT NOT NULL,
 evento_id INTEGER NOT NULL REFERENCES TRASEIRO_EVENTO(seq) ON DELETE RESTRICT,
 ativo INTEGER NOT NULL DEFAULT 0 CHECK (ativo IN (0,1)),
 ultima_tentativa TEXT,
 ultimo_sucesso TEXT,
 ultimo_erro TEXT,
 UNIQUE(origem,chave)
);
CREATE TABLE IF NOT EXISTS TRASEIRO_DECISAO (
 id BIGSERIAL PRIMARY KEY,
 evento_id INTEGER NOT NULL REFERENCES TRASEIRO_EVENTO(seq) ON DELETE RESTRICT,
 acao TEXT NOT NULL,
 quem TEXT NOT NULL,
 motivo TEXT NOT NULL,
 quando TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS TRASEIRO_PONTO_PENDENTE (
 ponto_id INTEGER PRIMARY KEY REFERENCES PONTO_FISCALIZACAO(id) ON DELETE CASCADE,
 revisao INTEGER NOT NULL DEFAULT 1 CHECK (revisao>0)
);
CREATE INDEX IF NOT EXISTS IX_TRASEIRO_CADASTRO_ESTADO ON TRASEIRO_CADASTRO(estado,id);
CREATE INDEX IF NOT EXISTS IX_TRASEIRO_EVENTO_ENTIDADE ON TRASEIRO_EVENTO(origem,tipo,chave,revisao);

CREATE OR REPLACE FUNCTION traseiro_ponto_fiscalizacao_insert_fn() RETURNS trigger AS $$
BEGIN
 IF EXISTS(SELECT 1 FROM TRASEIRO_LOCAL) THEN
 INSERT INTO TRASEIRO_PONTO_PENDENTE(ponto_id) SELECT NEW.id ON CONFLICT DO NOTHING;
 UPDATE TRASEIRO_PONTO_PENDENTE SET revisao=revisao+1 WHERE ponto_id IN (SELECT NEW.id);
 END IF;
 RETURN NULL;
END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS traseiro_ponto_fiscalizacao_insert ON PONTO_FISCALIZACAO;
CREATE TRIGGER traseiro_ponto_fiscalizacao_insert AFTER INSERT ON PONTO_FISCALIZACAO FOR EACH ROW EXECUTE FUNCTION traseiro_ponto_fiscalizacao_insert_fn();

