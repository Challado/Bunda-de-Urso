-- A origem e a chave são obtidas por meio da revisão a que pertencem.
CREATE TEMP TABLE VALIDAR_IDENTIDADE_MESH (ok INTEGER CONSTRAINT identidade_mesh_divergente CHECK(ok=1));
INSERT INTO VALIDAR_IDENTIDADE_MESH SELECT CASE WHEN EXISTS (SELECT 1 FROM TRASEIRO_CADASTRO c LEFT JOIN TRASEIRO_EVENTO e ON e.seq=c.evento_id
    WHERE e.seq IS NULL OR e.tipo<>'radar.v1' OR c.origem<>e.origem OR c.chave<>e.chave) THEN 0 ELSE 1 END;
DROP TABLE VALIDAR_IDENTIDADE_MESH;
CREATE TABLE TRASEIRO_CADASTRO_3FN (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 evento_id INTEGER NOT NULL REFERENCES TRASEIRO_EVENTO(seq) ON DELETE RESTRICT,
 validado_evento_id INTEGER REFERENCES TRASEIRO_EVENTO(seq) ON DELETE RESTRICT,
 ponto_id INTEGER REFERENCES PONTO_FISCALIZACAO(id) ON DELETE RESTRICT,
 estado TEXT NOT NULL DEFAULT 'pendente' CHECK (estado IN ('pendente','aprovado','rejeitado','retirado')),
 UNIQUE(evento_id)
);
INSERT INTO TRASEIRO_CADASTRO_3FN (id, evento_id, validado_evento_id, ponto_id, estado) SELECT id, evento_id, validado_evento_id, ponto_id, estado FROM TRASEIRO_CADASTRO;
UPDATE sqlite_sequence SET seq=MAX(seq,COALESCE((SELECT seq FROM sqlite_sequence WHERE UPPER(name)='TRASEIRO_CADASTRO'),0)) WHERE UPPER(name)='TRASEIRO_CADASTRO_3FN';
INSERT INTO sqlite_sequence(name,seq)
SELECT 'TRASEIRO_CADASTRO_3FN',seq FROM sqlite_sequence WHERE UPPER(name)='TRASEIRO_CADASTRO'
  AND NOT EXISTS (SELECT 1 FROM sqlite_sequence WHERE UPPER(name)='TRASEIRO_CADASTRO_3FN');
DROP TABLE TRASEIRO_CADASTRO;
ALTER TABLE TRASEIRO_CADASTRO_3FN RENAME TO TRASEIRO_CADASTRO;
CREATE TRIGGER CK_TRASEIRO_CADASTRO_INSERT AFTER INSERT ON TRASEIRO_CADASTRO
WHEN NOT EXISTS (SELECT 1 FROM TRASEIRO_EVENTO WHERE seq=NEW.evento_id AND tipo='radar.v1')
 OR EXISTS (SELECT 1 FROM TRASEIRO_CADASTRO d JOIN TRASEIRO_EVENTO a ON a.seq=d.evento_id
     JOIN TRASEIRO_EVENTO b ON b.seq=NEW.evento_id AND b.origem=a.origem AND b.chave=a.chave
     WHERE d.id<>NEW.id)
BEGIN SELECT RAISE(ABORT, 'identidade de evento mesh inválida ou duplicada'); END;
CREATE TRIGGER CK_TRASEIRO_CADASTRO_UPDATE AFTER UPDATE ON TRASEIRO_CADASTRO
WHEN NOT EXISTS (SELECT 1 FROM TRASEIRO_EVENTO WHERE seq=NEW.evento_id AND tipo='radar.v1')
