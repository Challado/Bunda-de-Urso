CREATE TRIGGER IF NOT EXISTS CK_REGISTRO_PAYLOAD_INSERT BEFORE INSERT ON REGISTRO_FONTE
WHEN NEW.hash_registro IS NULL
BEGIN SELECT RAISE(ABORT,'Registro exige payload'); END;
CREATE TRIGGER IF NOT EXISTS CK_REGISTRO_PAYLOAD_UPDATE BEFORE UPDATE OF hash_registro ON REGISTRO_FONTE
WHEN NEW.hash_registro IS NULL
BEGIN SELECT RAISE(ABORT,'Registro exige payload'); END;

CREATE VIEW IF NOT EXISTS REGISTRO_FONTE_DETALHE AS
SELECT r.*, p.payload_original FROM REGISTRO_FONTE r
LEFT JOIN PAYLOAD_FONTE p ON p.hash_registro=r.hash_registro;
