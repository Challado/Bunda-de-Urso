-- As consultas da API partem de um conjunto de pontos, posições ou execuções.
CREATE INDEX IF NOT EXISTS IX_POSICAO_LAT_LON ON POSICAO_GEOGRAFICA(latitude, longitude);
CREATE INDEX IF NOT EXISTS IX_PONTO_POSICAO ON PONTO_FISCALIZACAO(posicao_id);
CREATE INDEX IF NOT EXISTS IX_INSTALACAO_PONTO_EQUIPAMENTO ON INSTALACAO(ponto_id, equipamento_id);
CREATE INDEX IF NOT EXISTS IX_REGIME_PONTO ON REGIME_FISCALIZACAO(ponto_id);
CREATE INDEX IF NOT EXISTS IX_LIMITE_PONTO ON LIMITE_VELOCIDADE(ponto_id);
CREATE INDEX IF NOT EXISTS IX_LIMITE_FAIXA ON LIMITE_VELOCIDADE(faixa_id);
CREATE INDEX IF NOT EXISTS IX_ORGANIZACAO_PONTO ON PONTO_ORGANIZACAO(ponto_id);
CREATE INDEX IF NOT EXISTS IX_OPERACAO_PONTO ON OPERACAO_FISCALIZACAO(ponto_id);
CREATE INDEX IF NOT EXISTS IX_RECORRENCIA_OPERACAO ON OPERACAO_RECORRENCIA(operacao_id);
CREATE INDEX IF NOT EXISTS IX_EXECUCAO_RECURSO_RECENTE ON EXECUCAO_COLETA(recurso_id, id DESC);
CREATE INDEX IF NOT EXISTS IX_ERRO_EXECUCAO ON ERRO_VALIDACAO(execucao_id, id);

-- Uma linha por recurso, inclusive na primeira execução da agenda.
CREATE OR REPLACE VIEW ULTIMA_EXECUCAO_RECURSO AS
SELECT rf.id AS recurso_id,
       (SELECT e.id FROM EXECUCAO_COLETA e
        WHERE e.recurso_id=rf.id ORDER BY e.id DESC LIMIT 1) AS execucao_id
FROM RECURSO_FONTE rf;
