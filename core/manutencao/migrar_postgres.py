"""Copie a base SQLite do Radar Brasil para um esquema novo no PostgreSQL."""

import argparse
from contextlib import closing
from getpass import GetPassWarning, getpass
from graphlib import CycleError, TopologicalSorter
from pathlib import Path
import re
import sqlite3
import sys
from tempfile import TemporaryDirectory
import warnings

from core import caminhos, config, db, governanca
from core.contexto_api import operacao_local


class ErroMigracao(Exception):
    """Falha que pode ser exibida sem revelar dados da base."""


def verificar_sqlite(conn):
    if conn.execute("PRAGMA integrity_check").fetchone()[0] != "ok":
        raise ErroMigracao("A base SQLite falhou na checagem de integridade.")
    violacao = conn.execute("PRAGMA foreign_key_check").fetchone()
    if violacao:
        tabela, linha, pai, _ = violacao
        raise ErroMigracao(f"SQLite tem chave estrangeira inválida em {tabela}, linha {linha}, referência {pai}.")


def tabelas_sqlite(conn):
    return {r["name"].lower(): r["name"] for r in conn.execute(
        "SELECT name FROM sqlite_schema WHERE type='table' AND name NOT GLOB 'sqlite_*'")}


def preparar_origem(origem, destino):
    """Crie uma cópia consistente, incluindo WAL, e atualize o esquema da cópia."""
    with closing(db.connect_readonly(origem)) as fonte, closing(db.connect(destino)) as copia:
        fonte.backup(copia, pages=1024)
        verificar_sqlite(copia)
        if not db.esquema_carregado(copia):
            raise ErroMigracao("A origem não contém o esquema canônico do Radar Brasil.")
        governanca.aplicar_migracoes(copia)
        verificar_sqlite(copia)


def criar_esquema(conn, esquema):
    from psycopg import errors, sql

    if not re.fullmatch(r"[a-z][a-z0-9_]{0,62}", esquema) or esquema.startswith("pg_"):
        raise ErroMigracao("Use um nome de esquema com até 63 letras minúsculas, dígitos ou _.")
    if conn.info.server_version < 120000:
        raise ErroMigracao("O migrador requer PostgreSQL 12 ou superior.")
    # CREATE SCHEMA sem IF NOT EXISTS também recusa uma criação concorrente.
    try:
        conn.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(esquema)))
    except errors.DuplicateSchema as exc:
        raise ErroMigracao("O esquema de destino já existe. Escolha um nome novo.") from exc
    conn.execute(sql.SQL("SET LOCAL search_path TO {}").format(sql.Identifier(esquema)))
    conn.execute("SET LOCAL TimeZone TO 'UTC'")
    conn.execute("SET LOCAL DateStyle TO 'ISO, YMD'")
    conn.execute(Path(config.SCHEMA_POSTGRES).read_text(encoding="utf-8"))
    for arquivo in sorted((Path(config.SQL_DIR) / "migracoes").glob("*.postgres.sql")):
        conn.execute(arquivo.read_text(encoding="utf-8"))
    conn.execute("""
        CREATE TABLE migracao_governanca (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            versao TEXT NOT NULL UNIQUE,
            aplicada_em TEXT NOT NULL
        )
    """)
    # Triggers devem resolver as tabelas no esquema que os contém, inclusive
    # quando um cliente usa nomes qualificados e outro search_path.
    for (funcao,) in conn.execute("""
        SELECT p.proname FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
        WHERE n.nspname=%s AND p.prorettype='pg_catalog.trigger'::regtype
    """, (esquema,)):
        conn.execute(sql.SQL("ALTER FUNCTION {}() SET search_path FROM CURRENT")
                     .format(sql.Identifier(esquema, funcao)))


def catalogo_postgres(conn, esquema):
    colunas = {}
    for tabela, coluna in conn.execute("""
        SELECT c.table_name, c.column_name
        FROM information_schema.columns c
        JOIN information_schema.tables t USING (table_catalog, table_schema, table_name)
        WHERE c.table_schema=%s AND t.table_type='BASE TABLE'
        ORDER BY c.table_name, c.ordinal_position
    """, (esquema,)):
        colunas.setdefault(tabela, []).append(coluna)

    pais = {tabela: set() for tabela in colunas}
    for filha, pai in conn.execute("""
        SELECT filha.relname, pai.relname FROM pg_constraint fk
        JOIN pg_class filha ON filha.oid=fk.conrelid
        JOIN pg_class pai ON pai.oid=fk.confrelid
        WHERE fk.contype='f' AND filha.relnamespace=%s::regnamespace
          AND fk.conrelid<>fk.confrelid
    """, (esquema,)):
        pais[filha].add(pai)
    try:
        return colunas, tuple(TopologicalSorter(pais).static_order())
    except CycleError as exc:
        raise ErroMigracao("Há um ciclo entre tabelas de destino. Revise as migrações do esquema.") from exc


def conferir_colunas(origem, nomes, colunas):
    faltam = sorted(set(colunas) - set(nomes))
    extras = sorted(set(nomes) - set(colunas))
    if faltam or extras:
        raise ErroMigracao(f"Esquemas divergentes. Ausentes na origem: {faltam}. "
                           f"Sem destino: {extras}.")
    for tabela, campos in colunas.items():
        sqlite = {r["name"].lower() for r in origem.execute(
            "SELECT name FROM pragma_table_info(?)", (nomes[tabela],))}
        if sqlite != set(campos):
            raise ErroMigracao(f"Colunas divergentes em {tabela}: {sorted(sqlite ^ set(campos))}.")


def identificador_sqlite(nome):
    return '"' + nome.replace('"', '""') + '"'


def copiar_tabela(origem, destino, tabela, nome_sqlite, colunas):
    from psycopg import Error, sql

    campos = ", ".join(map(identificador_sqlite, colunas))
    seletor = f"SELECT {campos} FROM {identificador_sqlite(nome_sqlite)}"
    alvo = sql.Identifier(tabela)
    comando = sql.SQL("COPY {} ({}) FROM STDIN").format(
        alvo, sql.SQL(", ").join(map(sql.Identifier, colunas)))
    lidas = 0
    try:
        with destino.cursor().copy(comando) as copia:
            for linha in origem.execute(seletor):
                copia.write_row(tuple(linha))
                lidas += 1
    except Error as exc:
        # O contexto de COPY inclui o conteúdo do campo. Exiba apenas a linha
        # e o nome da coluna, quando estiverem disponíveis.
        contexto = (exc.diag.context or "").splitlines()[0:1]
        local = re.match(r"^COPY [\w.]+, line (\d+)(?:, column (\w+))?",
                         contexto[0] if contexto else "")
        detalhe = f", linha {local[1]}" if local else ""
        if local and local[2]:
            detalhe += f", coluna {local[2]}"
        raise ErroMigracao(f"Falha em {tabela}{detalhe} (SQLSTATE {exc.sqlstate or 'indisponível'}).") from exc

    gravadas, = destino.execute(sql.SQL("SELECT count(*) FROM {}").format(alvo)).fetchone()
    if lidas != gravadas:
        raise ErroMigracao(f"Contagens divergentes em {tabela}: {lidas} e {gravadas}.")
    return gravadas


def ajustar_sequencias(origem, destino, esquema):
    from psycopg import sql

    historico = {r[0].lower(): r[1] for r in origem.execute("SELECT name, seq FROM sqlite_sequence")}
    for tabela, coluna, sequencia in destino.execute("""
        SELECT t.relname, a.attname, s.oid FROM pg_class s
        JOIN pg_depend d ON d.objid=s.oid AND d.classid='pg_class'::regclass
                        AND d.refclassid='pg_class'::regclass AND d.deptype IN ('a','i')
        JOIN pg_class t ON t.oid=d.refobjid
        JOIN pg_attribute a ON a.attrelid=t.oid AND a.attnum=d.refobjsubid
        WHERE s.relkind='S' AND t.relnamespace=%s::regnamespace
    """, (esquema,)):
        maior, = destino.execute(sql.SQL("SELECT max({}) FROM {}").format(
            sql.Identifier(coluna), sql.Identifier(tabela))).fetchone()
        ultimo = max(maior or 0, historico.get(tabela) or 0)
        # Preserve IDs já consumidos no SQLite, inclusive após exclusões.
        destino.execute("SELECT pg_catalog.setval(%s::oid::regclass, %s, %s)",
                        (sequencia, max(1, ultimo), ultimo > 0))


def importar(origem, destino, esquema, simular=False, progresso=None):
    from psycopg import sql

    with destino.transaction(force_rollback=simular):
        criar_esquema(destino, esquema)
        colunas, ordem = catalogo_postgres(destino, esquema)
        nomes = tabelas_sqlite(origem)
        conferir_colunas(origem, nomes, colunas)

        # Triggers da rede geram novos eventos de origem. A cópia carrega a
        # própria fila existente, portanto só esses triggers ficam suspensos.
        gatilhos = list(destino.execute("""
            SELECT c.relname, t.tgname FROM pg_trigger t
            JOIN pg_class c ON c.oid=t.tgrelid
            WHERE c.relnamespace=%s::regnamespace AND NOT t.tgisinternal
              AND left(t.tgname, 9)='traseiro_'
        """, (esquema,)))
        for tabela, gatilho in gatilhos:
            destino.execute(sql.SQL("ALTER TABLE {} DISABLE TRIGGER {}").format(
                sql.Identifier(tabela), sql.Identifier(gatilho)))

        totais = {}
        for tabela in ordem:
            totais[tabela] = copiar_tabela(origem, destino, tabela, nomes[tabela], colunas[tabela])
            if progresso:
                progresso(tabela, totais[tabela])

        for tabela, gatilho in gatilhos:
            destino.execute(sql.SQL("ALTER TABLE {} ENABLE TRIGGER {}").format(
                sql.Identifier(tabela), sql.Identifier(gatilho)))
        ajustar_sequencias(origem, destino, esquema)
    return totais


@operacao_local
def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--origem", default=config.DB_PATH,
                        help="arquivo SQLite existente, dentro de [dados] dir")
    parser.add_argument("--host", help="endereço do PostgreSQL")
    parser.add_argument("--porta", type=int, default=5432)
    parser.add_argument("--banco", help="banco PostgreSQL existente")
    parser.add_argument("--usuario", help="usuário PostgreSQL com permissão CREATE no banco")
    parser.add_argument("--esquema", default="radar_brasil", help="nome de um esquema novo")
    parser.add_argument("--certificado-ca", help="CA do servidor, se ele usar uma CA própria")
    parser.add_argument("--simular", action="store_true", help="importe, valide e desfaça a transação")
    args = parser.parse_args(argv)

    try:
        import psycopg
    except ImportError:
        print("Instale psycopg 3 no Python utilizado para chamar api.pse.", file=sys.stderr)
        return 2

    try:
        try:
            origem = Path(caminhos.dentro_dados(args.origem, "origem SQLite"))
            ca = (caminhos.dentro_dados(args.certificado_ca, "certificado CA")
                  if args.certificado_ca else "system")
        except ValueError as exc:
            raise ErroMigracao(str(exc)) from exc
        if not origem.is_file():
            raise ErroMigracao("O arquivo SQLite de origem não existe.")
        if not sys.stdin.isatty():
            raise ErroMigracao("Execute em um terminal interativo para digitar a senha com segurança.")
        host = (args.host or input("Servidor PostgreSQL: ")).strip()
        banco = (args.banco or input("Nome do banco PostgreSQL: ")).strip()
        usuario = (args.usuario or input("Usuário PostgreSQL: ")).strip()
        if not all((host, banco, usuario)) or not 1 <= args.porta <= 65535:
            raise ErroMigracao("Informe servidor, banco, usuário e porta válidos.")
        with warnings.catch_warnings():
            warnings.simplefilter("error", GetPassWarning)
            senha = getpass("Senha PostgreSQL: ")
        print("Verificando conexão com PostgreSQL...", flush=True)
        try:
            destino = db.connect_postgres(host=host, port=args.porta, dbname=banco,
                                          user=usuario, password=senha, connect_timeout=10,
                                          sslmode="verify-full", sslrootcert=ca)
        except psycopg.OperationalError as exc:
            raise ErroMigracao("Conexão recusada. Confira endereço, porta, credenciais "
                               "e certificado TLS do PostgreSQL.") from exc
        finally:
            del senha
        with closing(destino), TemporaryDirectory(prefix="migrar-postgres-", dir=config.DATA_DIR) as temp:
            copia = Path(temp) / "origem.sqlite3"
            print("Preparando cópia consistente do SQLite...", flush=True)
            preparar_origem(origem, copia)
            with closing(db.connect_readonly(copia)) as fonte:
                totais = importar(fonte, destino, args.esquema, simular=args.simular,
                                  progresso=lambda t, n: print(f"{t}: {n} linhas", flush=True))
        estado = "Simulação validada e desfeita" if args.simular else "Migração concluída"
        print(f"{estado}. Esquema {args.esquema}: {len(totais)} tabelas, {sum(totais.values())} linhas.")
        return 0
    except ErroMigracao as exc:
        print(f"Migração interrompida: {exc}", file=sys.stderr)
    except GetPassWarning:
        print("Migração interrompida: não foi possível ocultar a senha neste terminal.", file=sys.stderr)
    except (sqlite3.Error, psycopg.Error, OSError) as exc:
        # Evite mensagens de drivers com valores de linhas ou credenciais.
        codigo = getattr(exc, "sqlstate", None) or getattr(exc, "sqlite_errorname", None)
        detalhe = f" ({codigo})" if codigo else ""
        print(f"Migração interrompida: {type(exc).__name__}{detalhe}.", file=sys.stderr)
    except (KeyboardInterrupt, EOFError):
        print("\nMigração interrompida pelo operador.", file=sys.stderr)
    return 1
